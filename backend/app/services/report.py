"""Builds the risk report from REAL computed values using fixed templates (no LLM)."""
from datetime import datetime, timezone
from . import market_data as md, risk

LIMITATIONS = [
    "Historical performance does not guarantee future results.",
    "Volatility and drawdown describe the past only; they do not predict future price movements.",
    "Closing prices from the free data tier are not adjusted for splits or dividends, so such events can distort returns.",
    "Risk categories use configurable demonstration thresholds, not universal definitions of risk.",
    "StockShield is an educational tool and does not provide personalised financial advice.",
]

METRIC_INFO = {
    "pe": ("Price-to-earnings ratio", "x", "Price relative to earnings per share. A low P/E does not automatically mean a stock is undervalued, and P/E varies widely between industries."),
    "debt_to_equity": ("Debt-to-equity ratio", "x", "A high ratio may indicate greater financial leverage. Not provided by the configured data source."),
    "revenue_growth": ("Revenue growth (quarterly, YoY)", "%", "Positive revenue growth does not guarantee future profitability."),
    "earnings_growth": ("Earnings growth (quarterly, YoY)", "%", "Earnings can be volatile; one quarter says little about long-term trends."),
    "profit_margin": ("Profit margin", "%", "Share of revenue kept as profit. Typical margins differ strongly by industry."),
    "operating_cash_flow": ("Operating cash flow", "", "Cash generated by core operations. Not provided by the configured data source."),
    "market_cap": ("Market capitalisation", "", "Total market value of shares. Larger companies are not automatically safer."),
    "dividend_yield": ("Dividend yield", "%", "Annual dividends relative to price. A high yield can also reflect a falling price."),
}


def prepare(symbol, period):
    raw = md.daily_series(symbol)
    full = risk.clean_prices(raw["points"])
    if full.empty:
        raise md.MarketDataError(404, "no_data", "No valid price observations were returned for this symbol.")
    s = risk.slice_period(full, period)
    requested = risk.PERIOD_DAYS[period]
    available = (full.index[-1] - full.index[0]).days
    warning = None
    if available < requested - 5:
        warning = (f"The data source returned about {available} days of history, which is less than the {requested} days "
                   f"needed for the '{period}' period. Results use the available data only.")
    return raw, full, s, dropped_count(raw, full), warning, requested, available


def dropped_count(raw, full): return max(0, len(raw["points"]) - len(full))


def fundamentals_block(symbol):
    try:
        f = md.fundamentals(symbol)
    except md.MarketDataError as e:
        return None, [], f"Fundamentals unavailable: {e.message}"
    pct = lambda v: None if v is None else v * 100
    vals = {"pe": f["pe"], "debt_to_equity": None, "revenue_growth": pct(f["revenue_growth"]),
            "earnings_growth": pct(f["earnings_growth"]), "profit_margin": pct(f["profit_margin"]),
            "operating_cash_flow": None, "market_cap": f["market_cap"], "dividend_yield": pct(f["dividend_yield"])}
    metrics = []
    for k, (label, unit, expl) in METRIC_INFO.items():
        v = vals[k]
        metrics.append({"key": k, "label": label, "value": None if v is None else round(v, 2), "unit": unit,
                        "as_of": f["as_of"], "explanation": expl, "available": v is not None})
    return f, metrics, None


def build_report(symbol, period):
    raw, full, s, dropped, warning, requested, available = prepare(symbol, period)
    r = risk.daily_returns(s)
    vol, mdd = risk.annualised_vol(r), risk.max_drawdown(s)
    prof = risk.classify(vol, mdd["value"] if mdd else None, len(r))
    f, metrics, fund_warning = fundamentals_block(symbol)
    name = (f or {}).get("name") or symbol
    warnings = []
    if raw["demo"]: warnings.append("DEMO DATA — NOT LIVE MARKET DATA.")
    if warning: warnings.append(warning)
    if dropped: warnings.append(f"{dropped} invalid or duplicate observation(s) were removed.")
    if len(r) < risk.THRESHOLDS["min_obs_vol"]: warnings.append("Too few observations for a reliable volatility estimate.")
    if fund_warning: warnings.append(fund_warning)
    missing = [m["label"] for m in metrics if not m["available"]]
    if missing: warnings.append("Data unavailable for: " + ", ".join(missing) + ".")

    factors = []
    if prof["volatility_category"] and prof["volatility_category"].startswith("Higher"):
        factors.append("Daily returns have been highly variable (higher historical volatility).")
    if prof["drawdown_category"] and prof["drawdown_category"].startswith("Higher"):
        factors.append("The price has experienced a large peak-to-trough decline in the analysed data.")
    if len(r) < risk.THRESHOLDS["min_obs_confident"]:
        factors.append("The analysed history is short, so the statistics may not represent longer-term behaviour.")
    for m in metrics:
        if m["key"] in ("profit_margin", "earnings_growth") and m["value"] is not None and m["value"] < 0:
            factors.append(f"{m['label']} is negative ({m['value']}%).")
    if not factors:
        factors.append("The rules flagged no elevated indicators in the available data, which does not mean the stock is safe.")

    ret = risk.period_return(s)
    fmt = lambda v: "unavailable" if v is None else f"{v:.2f}%"
    summary = (f"Over the '{period}' window ({s.index[0].date()} to {s.index[-1].date()}, {len(s)} daily closes), {name} ({symbol}) "
               f"had a price return of {fmt(ret)}, annualised historical volatility of {fmt(vol)} and a maximum drawdown of "
               f"{fmt(mdd['value'] if mdd else None)}. Historical risk profile: {prof['profile']} (data confidence: {prof['data_confidence']}). "
               "This describes the past only and is not a prediction or advice.")
    return {
        "symbol": symbol, "company_name": name, "analysis_period": period,
        "analysed_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "provider": raw["provider"], "demo": raw["demo"], "price_frequency": "daily close",
        "data_start": s.index[0].date().isoformat(), "data_end": s.index[-1].date().isoformat(),
        "observations": int(len(s)), "latest_price": float(full.iloc[-1]), "latest_price_date": full.index[-1].date().isoformat(),
        "currency": (f or {}).get("currency"),
        "returns": {"period_pct": ret, "1m_pct": risk.window_return(full, 30), "3m_pct": risk.window_return(full, 90),
                    "1y_pct": risk.window_return(full, 365)},
        "avg_daily_return_pct": None if r.empty else float(r.mean() * 100),
        "annualised_volatility_pct": vol, "volatility_explanation": risk.explain_volatility(vol),
        "max_drawdown": mdd, "drawdown_explanation": risk.explain_drawdown(mdd),
        "risk_profile": prof, "fundamentals": metrics, "warnings": warnings,
        "risk_factors": factors, "limitations": LIMITATIONS, "summary": summary,
        "methodology": {"annualisation_days": risk.TRADING_DAYS, "thresholds": risk.THRESHOLDS},
    }
